#!/usr/bin/env python3
"""Validate nutrition coverage/provenance and generate an insert-only SQL import."""
import argparse
import csv
from datetime import date
from decimal import Decimal, InvalidOperation
from pathlib import Path
import re
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'Database/catalog/ingredient_nutrition.csv'
OUTPUT = ROOT / 'Database/seeds/catalog_nutrition_seed.sql'
MACROS = ('calories', 'protein_g', 'carbs_g', 'fat_g')
METADATA = {'name', 'status', 'basis_unit', 'source_url', 'source_description', 'energy_method', 'notes', 'reviewed_on'}


def read_catalog():
    with SOURCE.open(encoding='utf-8', newline='') as stream:
        rows = list(csv.DictReader(stream))
    with (ROOT / 'Database/catalog/moldova_ingredients.csv').open(encoding='utf-8') as stream:
        names = {r['name'] for r in csv.DictReader(stream)}
    names.update(re.findall(r"\(N'([^']+)',\s+N'[^']+'\)", (ROOT / 'Database/seeds/ingredients_seed.sql').read_text()))
    if len(rows) != len(names) or {r['name'] for r in rows} != names:
        raise ValueError('Nutrition review must cover every catalog name exactly once')
    for row in rows:
        date.fromisoformat(row['reviewed_on'])
        if row['status'] not in ('reference', 'label', 'needs_label'):
            raise ValueError(f"Unknown status: {row['name']}")
        if row['status'] == 'needs_label':
            if not row['notes'] or any(row[k] for k in MACROS):
                raise ValueError('Unverified nutrition requires a reason and blank macro values')
            continue
        url = urlparse(row['source_url'])
        if url.scheme != 'https' or not url.hostname or not row['source_description']:
            raise ValueError(f"Missing provenance: {row['name']}")
        if row['basis_quantity'] != '100' or row['basis_unit'] not in ('g', 'ml'):
            raise ValueError(f"Nonstandard basis: {row['name']}")
        if not all(row[k] != '' for k in MACROS):
            raise ValueError(f"Missing macro: {row['name']}")
        for key, value in row.items():
            if key in METADATA or value == '':
                continue
            try:
                number = Decimal(value)
                if not number.is_finite() or number < 0:
                    raise ValueError(f'Invalid {key}: {value}')
            except InvalidOperation as error:
                raise ValueError(f'Invalid {key}: {value}') from error
        if any(Decimal(row[k]) > 100 for k in ('protein_g', 'carbs_g', 'fat_g')) or Decimal(row['calories']) > 950:
            raise ValueError(f"Implausible macros: {row['name']}")
        if sum(Decimal(row[k]) for k in ('protein_g', 'carbs_g', 'fat_g')) > Decimal('102'):
            raise ValueError(f"Macros exceed food mass: {row['name']}")
        if row['saturated_fat_g'] and Decimal(row['saturated_fat_g']) > Decimal(row['fat_g']) + Decimal('.05'):
            raise ValueError(f"Saturates exceed total fat: {row['name']}")
        if row['energy_method'] not in ('source', 'source_specific_atwater', 'calculated_4_4_9'):
            raise ValueError(f"Missing energy method: {row['name']}")
        if row['energy_method'] == 'calculated_4_4_9':
            expected = 4*Decimal(row['protein_g']) + 4*Decimal(row['carbs_g']) + 9*Decimal(row['fat_g'])
            if abs(Decimal(row['calories']) - expected) > Decimal('.01'):
                raise ValueError(f"Energy estimate disagrees with macros: {row['name']}")
    return rows


def generate(rows):
    def q(value):
        return "N'" + value.replace("'", "''") + "'"
    values = []
    for row in rows:
        if row['status'] == 'needs_label':
            continue
        values.append('    (' + ', '.join([q(row['name']), q(row['basis_unit'])] +
            [str(Decimal(row[k]).quantize(Decimal('.01'))) for k in MACROS] +
            [q(row['source_url']), q(row['source_description'])]) + ')')
    return '''-- Generated by scripts/generate-ingredient-nutrition.py from the reviewed CSV.
-- Per 100 g edible portion unless explicitly marked ml. No density assumptions.
-- Generic references/representative labels are estimates; see source descriptions and notes.
-- Existing nutrition (including custom edits and starter defaults) is never overwritten.
USE MealPrepDB;
GO
SET NOCOUNT ON;
SET XACT_ABORT ON;
BEGIN TRY
    BEGIN TRAN;
    DECLARE @Source TABLE (
        Name nvarchar(100) PRIMARY KEY, UnitAbbr nvarchar(10), Calories decimal(10,2),
        Protein decimal(10,2), Carbs decimal(10,2), Fat decimal(10,2),
        SourceUrl nvarchar(1000), SourceDescription nvarchar(500));
    INSERT @Source VALUES
''' + ',\n'.join(values) + ''';
    IF EXISTS (SELECT 1 FROM @Source s LEFT JOIN dbo.Ingredients i ON i.Name=s.Name
        LEFT JOIN dbo.Units u ON u.Abbreviation=s.UnitAbbr
        WHERE i.IngredientID IS NULL OR u.UnitID IS NULL)
        THROW 51000, N'Nutrition import requires the complete ingredient catalog and basis units.', 1;

    DECLARE @Added TABLE (IngredientID int PRIMARY KEY);
    INSERT dbo.IngredientNutrition
        (IngredientID, BasisQuantity, BasisUnitID, Calories, ProteinGrams, CarbsGrams, FatGrams, UpdatedAt)
    OUTPUT inserted.IngredientID INTO @Added
    SELECT i.IngredientID, 100, u.UnitID, s.Calories, s.Protein, s.Carbs, s.Fat, SYSUTCDATETIME()
    FROM @Source s JOIN dbo.Ingredients i ON i.Name=s.Name
    JOIN dbo.Units u ON u.Abbreviation=s.UnitAbbr
    WHERE NOT EXISTS (SELECT 1 FROM dbo.IngredientNutrition n WITH (UPDLOCK,HOLDLOCK)
        WHERE n.IngredientID=i.IngredientID);

    INSERT dbo.AuditLog (Action, EntityType, EntityID, Details, CreatedAt)
    SELECT N'INGREDIENT_NUTRITION_SET', N'Ingredient', a.IngredientID,
        LEFT(N'Catalog nutrition 2026-11-11: ' + s.SourceDescription + N'; ' + s.SourceUrl, 500), SYSUTCDATETIME()
    FROM @Added a JOIN dbo.Ingredients i ON i.IngredientID=a.IngredientID
    JOIN @Source s ON s.Name=i.Name;
    COMMIT;
    SELECT COUNT(*) AS NutritionRowsAdded FROM @Added;
END TRY
BEGIN CATCH
    IF XACT_STATE() <> 0 ROLLBACK;
    THROW;
END CATCH;
GO
'''


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    rows = read_catalog()
    content = generate(rows)
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != content:
            raise SystemExit('Nutrition SQL is stale; run scripts/generate-ingredient-nutrition.py')
    else:
        OUTPUT.write_text(content)
    print(f"Reviewed {len(rows)} ingredients: {sum(r['status'] != 'needs_label' for r in rows)} complete profiles; "
          f"{sum(r['status'] == 'needs_label' for r in rows)} unresolved entries.")
