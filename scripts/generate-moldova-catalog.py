#!/usr/bin/env python3
"""Validate retailer provenance and generate the additive ingredient seed."""
import argparse
import csv
from datetime import date
from pathlib import Path
import re
import unicodedata
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / 'Database/catalog/moldova_ingredients.csv'
OUTPUT = ROOT / 'Database/seeds/moldova_ingredients_seed.sql'


def normalized(value):
    return ''.join(c for c in unicodedata.normalize('NFD', value.casefold())
                   if not unicodedata.combining(c)).strip()


def generate():
    rows = list(csv.DictReader(CATALOG.open(encoding='utf-8')))
    existing = set(re.findall(r"\(N'([^']+)'", (ROOT / 'Database/seeds/ingredients_seed.sql').read_text()))
    categories = set(re.findall(r"\(N'([^']+)'\)", (ROOT / 'Database/seeds/ingredient_categories_seed.sql').read_text()))
    seen = {normalized(name) for name in existing}
    for row in rows:
        name = row['name']
        if not name or name != name.strip() or len(name) > 100 or normalized(name) in seen:
            raise ValueError(f'Duplicate or invalid ingredient: {name}')
        seen.add(normalized(name))
        if row['category'] not in categories or row['unit'] not in ('g', 'ml', 'pc'):
            raise ValueError(f'Invalid category/unit: {name}')
        source = urlparse(row['source_url'])
        if source.scheme != 'https' or not source.hostname or not source.hostname.endswith('.md') or not row['evidence']:
            raise ValueError(f'Missing Moldovan retailer evidence: {name}')
        date.fromisoformat(row['checked_on'])
    def quote(value):
        return "N'" + value.replace("'", "''") + "'"
    values = ',\n'.join('    (' + ', '.join(quote(row[key]) for key in ('name', 'unit', 'category')) + ')' for row in rows)
    return '''-- Generated by scripts/generate-moldova-catalog.py. Edit the source CSV instead.
-- Retailer evidence: Database/catalog/moldova_ingredients.csv.
-- Insert only: preserve existing IDs, units, categories and nutrition, including custom rows.
-- Missing nutrition remains unknown, never a zero-calorie placeholder.
USE MealPrepDB;
GO
SET NOCOUNT ON;
SET XACT_ABORT ON;
BEGIN TRY
    BEGIN TRAN;
    DECLARE @Catalog TABLE (Name nvarchar(100) PRIMARY KEY, UnitAbbr nvarchar(10), CategoryName nvarchar(100));
    INSERT @Catalog (Name, UnitAbbr, CategoryName) VALUES
''' + values + ''';

    IF EXISTS (
        SELECT 1 FROM @Catalog s
        LEFT JOIN dbo.Units u ON u.Abbreviation = s.UnitAbbr
        LEFT JOIN dbo.IngredientCategories c ON c.Name = s.CategoryName
        WHERE u.UnitID IS NULL OR c.IngredientCategoryID IS NULL
    ) THROW 51000, N'Ingredient catalog requires seeded units and ingredient categories.', 1;

    DECLARE @Added TABLE (IngredientID int, Name nvarchar(100));
    INSERT dbo.Ingredients (Name, DefaultUnitID, IngredientCategoryID)
    OUTPUT inserted.IngredientID, inserted.Name INTO @Added
    SELECT s.Name, u.UnitID, c.IngredientCategoryID
    FROM @Catalog s
    JOIN dbo.Units u ON u.Abbreviation = s.UnitAbbr
    JOIN dbo.IngredientCategories c ON c.Name = s.CategoryName
    WHERE NOT EXISTS (SELECT 1 FROM dbo.Ingredients i WITH (UPDLOCK, HOLDLOCK) WHERE i.Name = s.Name);

    INSERT dbo.AuditLog (Action, EntityType, EntityID, Details, CreatedAt)
    SELECT N'INGREDIENT_ADD', N'Ingredient', IngredientID,
        N'Moldova retailer catalog 2026-11-11: ' + Name, SYSUTCDATETIME()
    FROM @Added;
    COMMIT;
    SELECT COUNT(*) AS IngredientsAdded FROM @Added;
END TRY
BEGIN CATCH
    IF XACT_STATE() <> 0 ROLLBACK;
    THROW;
END CATCH;
GO
'''


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if generated SQL is stale')
    args = parser.parse_args()
    content = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != content:
            raise SystemExit('Catalog SQL is stale; run scripts/generate-moldova-catalog.py')
        print('Catalog provenance, names, categories, units and generated SQL verified.')
    else:
        OUTPUT.write_text(content)
        print(f'Generated {OUTPUT.relative_to(ROOT)}')
