 ContentHash BINARY(32) NOT NULL,CreatedAt DATETIME2(7) NOT NULL DEFAULT SYSUTCDATETIME(),ExpiresAt DATETIME2(7) NOT NULL DEFAULT DATEADD(HOUR,24,SYSUTCDATETIME()));
IF OBJECT_ID(N'dbo.AssistantAcceptedRows',N'U') IS NULL
