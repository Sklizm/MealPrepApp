IF OBJECT_ID(N'dbo.AssistantPreferences',N'U') IS NULL
 CREATE TABLE dbo.AssistantPreferences(UserID INT PRIMARY KEY REFERENCES dbo.Users(UserID),PreferencesJson NVARCHAR(MAX) NOT NULL CHECK(ISJSON(PreferencesJson)=1),
 NoticeVersion NVARCHAR(30) NULL,AcceptedAt DATETIME2(7) NULL,Version BIGINT NOT NULL DEFAULT 1,UpdatedAt DATETIME2(7) NOT NULL DEFAULT SYSUTCDATETIME());
IF OBJECT_ID(N'dbo.AssistantJobs',N'U') IS NULL
BEGIN
 CREATE TABLE dbo.AssistantJobs(JobID UNIQUEIDENTIFIER PRIMARY KEY,UserID INT NOT NULL REFERENCES dbo.Users(UserID),SessionID UNIQUEIDENTIFIER NOT NULL REFERENCES dbo.DeviceSessions(SessionID),
 Kind NVARCHAR(20) NOT NULL,State NVARCHAR(20) NOT NULL DEFAULT N'Queued',Version BIGINT NOT NULL DEFAULT 1,
 WorkJson NVARCHAR(MAX) NULL,ResultJson NVARCHAR(MAX) NULL,ErrorCode NVARCHAR(80) NULL,RequestHash BINARY(32) NOT NULL,
 InputTokens INT NOT NULL DEFAULT 0,OutputTokens INT NOT NULL DEFAULT 0,CreatedAt DATETIME2(7) NOT NULL DEFAULT SYSUTCDATETIME(),
 ExpiresAt DATETIME2(7) NOT NULL DEFAULT DATEADD(DAY,7,SYSUTCDATETIME()));
 CREATE INDEX IX_AssistantJobs_Owner ON dbo.AssistantJobs(UserID,CreatedAt DESC);
END;
IF OBJECT_ID(N'dbo.AssistantUploads',N'U') IS NULL
