IF OBJECT_ID(N'dbo.DeviceSessions',N'U') IS NULL
BEGIN
 CREATE TABLE dbo.DeviceSessions(SessionID UNIQUEIDENTIFIER PRIMARY KEY,UserID INT NOT NULL REFERENCES dbo.Users(UserID),
 TokenHash BINARY(32) NOT NULL UNIQUE,CredentialHash BINARY(32) NOT NULL,RequestHash BINARY(32) NOT NULL,
 DeviceName NVARCHAR(80) NOT NULL,CreatedAt DATETIME2(7) NOT NULL DEFAULT SYSUTCDATETIME(),ExpiresAt DATETIME2(7) NOT NULL,RevokedAt DATETIME2(7) NULL);
 CREATE INDEX IX_DeviceSessions_User ON dbo.DeviceSessions(UserID,CreatedAt DESC);
END;
